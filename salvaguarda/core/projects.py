@dataclass
class _Dir:
    path: str
    rel: Optional[str]
    depth: int
    mode: int
    owner: Optional[str]
    below_owner: int
    dev: int
    by_path: bool  # mount points can be recognised by path (no symlink in the root)


def _compile_skip(patterns: Sequence[str]) -> "re.Pattern":
    # The anchor applies to the whole alternation: "snap" must not skip ~/snapshots.
    if not patterns:
        return re.compile(r"(?!)")
    body = "|".join("(?:%s)" % glob_to_regex(p.rstrip("/")) for p in patterns)
    return re.compile(r"(?:%s)\Z" % body, re.DOTALL)


def _decode_mount(raw: bytes) -> str:
    return os.fsdecode(re.sub(rb"\\([0-7]{3})", lambda m: bytes((int(m.group(1), 8),)), raw))


NETWORK_FS = frozenset((
    "nfs", "nfs4", "cifs", "smb3", "smbfs", "ncpfs", "afs", "ceph", "glusterfs", "9p",
    "davfs", "fuse.sshfs", "fuse.rclone", "fuse.davfs2", "fuse.gvfsd-fuse", "fuse.s3fs",
    "fuse.gcsfuse", "fuse.curlftpfs", "fuse.onedriver", "fuse.google-drive-ocamlfuse",
))


def mount_table(path: str = "/proc/self/mountinfo") -> List[Tuple[str, int, str]]:
    """(mount point, device number, file system type), read without touching the mounts.

    A stat() on a disconnected network mount (sshfs, rclone) can hang, so the walk
    recognises mount points by name instead.
    """
    result: List[Tuple[str, int, str]] = []
    try:
        with open(path, "rb") as fh:
            for line in fh:
                parts = line.rstrip(b"\n").split(b" ")
                if len(parts) < 5:
                    continue
                try:
                    major, minor = parts[2].split(b":")
                    dev = os.makedev(int(major), int(minor))
                except ValueError:
                    continue
                fstype = ""
                if b"-" in parts[5:]:
                    sep = parts.index(b"-", 5)
                    if sep + 1 < len(parts):
                        fstype = parts[sep + 1].decode("ascii", "replace")
                result.append((_decode_mount(parts[4]), dev, fstype))
    except OSError:
        return []
    return result


def mount_points(path: str = "/proc/self/mountinfo") -> Dict[str, int]:
    """Mount point -> device number (the last mount on a path wins, as in the kernel)."""
    return {mnt: dev for mnt, dev, _ in mount_table(path)}


def network_mount(path: str, table: Sequence[Tuple[str, int, str]]) -> str:
    """The network mount that holds ``path`` ("" if none), following symbolic links
    only on local file systems so that a dead server is never touched."""
    network = {mnt for mnt, _, fstype in table if fstype in NETWORK_FS}
    if not network:
        return ""
    current = os.path.normpath(os.path.abspath(path))
    for _ in range(40):
        parts = current.split(os.sep)
        prefix = os.sep
        restart = False
        for i, part in enumerate(parts[1:], 1):
            prefix = os.path.join(prefix, part)
            if prefix in network:
                return prefix
            try:
                is_link = os.path.islink(prefix)
            except OSError:
                return ""
            if is_link:
                try:
                    target = os.readlink(prefix)
                except OSError:
                    return ""
                rest = parts[i + 1:]
                base = os.path.dirname(prefix)
                current = os.path.normpath(os.path.join(base, target, *rest))
                restart = True
                break
        if not restart:
            return ""
    return ""


def _marker_names(names: Set[str], dir_names: Set[str]) -> List[str]:
    found = [n for n in names
             if n in STRONG_MARKERS or n.startswith(CONFIG_PREFIXES) or n.endswith(SUFFIX_MARKERS)]
    if found:
        return sorted(found)[:6]
    weak = [n for n in names if n in WEAK_MARKERS]
    if not weak:
        return []
    others = 0
    for n in names:
        if n not in WEAK_MARKERS and os.path.splitext(n)[1].lower() in CODE_EXTENSIONS:
            others += 1
            break
    if len(weak) >= 2 or others or dir_names & CODE_DIRS:
        return sorted(weak)[:6]
    return []


def _is_bare_repo(names: Set[str], dir_names: Set[str]) -> bool:
    return "HEAD" in names and "config" in names and {"objects", "refs"} <= dir_names


class _Walker:
    def __init__(self, home: str, excl: Exclusions, limits: Limits,
                 cancel: Optional[threading.Event], progress: Optional[Callable],
                 mounts: Dict[str, int], skip: Sequence[str]):
        self.home = home
        self.excl = excl
        self.limits = limits
        self.cancel = cancel
        self.progress = progress
        self.mounts = mounts
        self.skip = _compile_skip(skip)
        self.containers = {os.path.normpath(p) for p in paths.xdg_user_dirs().values()}
        self.containers.add(home)
        self.result = ScanResult()
        self.found: Dict[str, Project] = {}
        self.watch: Set[str] = set()     # extra roots: noted when the home walk lists them
        self.listed_watch: Set[str] = set()
        self.started = time.monotonic()
        self._last_progress = 0.0

    # -- budget ------------------------------------------------------------------
    def _over_budget(self) -> bool:
        if self.cancel is not None and self.cancel.is_set():
            self.result.cancelled = True
            return True
        if self.result.entries >= self.limits.max_entries:
            return True
        return time.monotonic() - self.started > self.limits.time_budget

    def walk(self, root: str, rel: Optional[str], mode: int = MODE_FULL) -> None:
        try:
            st = os.stat(root)
        except OSError:
            return
        if not os.path.isdir(root):
            return
        by_path = bool(self.mounts) and os.path.realpath(root) == os.path.normpath(root)
        queue: Deque[_Dir] = deque([_Dir(root, rel, 0, mode, None, 0, st.st_dev, by_path)])
        while queue:
            if self._over_budget():
                self.result.truncated = not self.result.cancelled
                for item in list(queue)[:_SAMPLE - len(self.result.unfinished)]:
                    self.result.unfinished.append(item.path)
                return
            self._visit(queue.popleft(), queue, root)

    def _visit(self, item: _Dir, queue: Deque[_Dir], root: str) -> None:
        res = self.result
        try:
            with os.scandir(item.path) as it:
                entries = list(it)
        except OSError:
            res.unreadable_count += 1
            if len(res.unreadable) < _SAMPLE:
                res.unreadable.append(item.path)
            return
        res.dirs += 1
        res.entries += len(entries)
        selected = item.depth > 0 and item.path in self.watch
        depth = item.depth
        if selected:
            # A selected folder is searched in full from where it starts, even when it
            # is deep or hidden (the backup copies all of it).
            self.listed_watch.add(item.path)
            item.mode = MODE_FULL
            depth = 0
        now = time.monotonic()
        if self.progress is not None and now - self._last_progress > 0.25:
            self._last_progress = now
            self.progress(res.dirs, res.entries, item.path)

        names: Set[str] = set()
        dirs: List[os.DirEntry] = []
        for entry in entries:
            names.add(entry.name)
            try:
                if entry.is_dir(follow_symlinks=False):
                    dirs.append(entry)
            except OSError:
                continue
        dir_names = {e.name for e in dirs}

        if item.depth > 0 and not selected and self.excl.match_listing(item.path, names) is not None:
            res.excluded_dirs += 1  # virtual environment or tagged cache
            return

        owner, below = item.owner, item.below_owner
        is_container = item.path in self.containers or (
            item.depth == 1 and item.path.startswith(self.home + os.sep)
            and os.path.basename(item.path).lower() in catalog.PROJECT_FOLDER_NAMES)
        if ".git" in names:
            project = self._add(item.path, KIND_GIT, owner)
            if project is not None:
                project.home_repo = item.path == self.home
                if not is_container:
                    owner, below = item.path, 0
        elif _is_bare_repo(names, dir_names) and item.depth > 0:
            self._add(item.path, KIND_BARE, owner)
            return  # objects/ and refs/ hold nothing else of interest
        elif item.mode == MODE_FULL and owner is None and not is_container:
            markers = _marker_names(names, dir_names)
            if markers:
                project = self._add(item.path, KIND_FOLDER, None)
                if project is not None:
                    project.markers = markers
                    owner, below = item.path, 0

        limit = self.limits.max_depth if item.mode == MODE_FULL else self.limits.hidden_depth
        for entry in dirs:
            name = entry.name
            if name == ".git":
                continue
            child = entry.path
            child_rel = None if item.rel is None else (name if item.rel == "" else item.rel + "/" + name)
            if self.excl.match(name, child, child_rel, True) is not None:
                res.excluded_dirs += 1
                continue
            if child_rel is not None and self.skip.match(child_rel):
                res.excluded_dirs += 1
                continue
            if item.by_path:
                dev = self.mounts.get(child)
                other = dev is not None and dev != item.dev
            else:
                try:
                    other = entry.stat(follow_symlinks=False).st_dev != item.dev
                except OSError:
                    continue
            if other:
                if len(res.other_filesystems) < _SAMPLE:
                    res.other_filesystems.append(child)
                continue
            if owner is not None and below + 1 > self.limits.nested_depth:
                continue
            if depth + 1 > limit:
                res.too_deep_count += 1
                if len(res.too_deep) < _SAMPLE:
                    res.too_deep.append(child)
                continue
            mode = item.mode
            if item.depth == 0 and item.path == self.home and name.startswith("."):
                mode = MODE_GIT
            queue.append(_Dir(child, child_rel, depth + 1, mode, owner,
                              below + 1 if owner is not None else 0, item.dev, item.by_path))

    def _add(self, path: str, kind: str, owner: Optional[str]) -> Optional[Project]:
        if path in self.found:
            return None
        project = Project(path, kind, parent=owner)
        if kind == KIND_GIT:
            project.gitdir, project.common_dir = git_dirs(path)
            if project.gitdir is not None:
                project.worktree = os.path.basename(os.path.dirname(project.gitdir)) == "worktrees"
                project.submodule = (os.sep + "modules" + os.sep) in project.gitdir
        elif kind == KIND_BARE:
            project.gitdir = project.common_dir = path
        self.found[path] = project
        return project


# ------------------------------------------------------------------- git, read-only
def git_dirs(root: str) -> Tuple[Optional[str], Optional[str]]:
    """(git dir, common dir) of the work tree ``root``, read from disk without git."""
    dotgit = os.path.join(root, ".git")
    try:
        if os.path.isdir(dotgit):
            gitdir = dotgit
        else:
            with open(dotgit, "rb") as fh:
                head = fh.read(4096)
            if not head.startswith(b"gitdir:"):
                return None, None
            lines = head[7:].strip().splitlines()
            if not lines:
                return None, None
            gitdir = os.path.normpath(os.path.join(root, os.fsdecode(lines[0].strip())))
    except OSError:
        return None, None
    common = gitdir
    try:
        with open(os.path.join(gitdir, "commondir"), "rb") as fh:
            rel = fh.read().strip()
        if rel:
            common = os.path.normpath(os.path.join(gitdir, os.fsdecode(rel)))
    except OSError:
        pass
    if not os.path.isfile(os.path.join(gitdir, "HEAD")) or not os.path.isdir(
            os.path.join(common, "objects")):
        return None, None
    return gitdir, common


_SECTION = re.compile(r'^\s*\[\s*([A-Za-z0-9.-]+)(?:\s+"((?:[^"\\\n]|\\.)*)")?\s*\](.*)$')
_KEYVAL = re.compile(r'^\s*([A-Za-z][A-Za-z0-9-]*)\s*(?:=\s*(.*?))?\s*$')


def read_git_config(path: str) -> Tuple[List[Tuple[str, str]], List[str], bool]:
    """(remotes as (name, url), filter driver names, has includes) from one config file."""
    remotes: Dict[str, str] = {}
    filters: List[str] = []
    includes = False
    section, sub = "", None
    try:
        with open(path, encoding="utf-8", errors="surrogateescape") as fh:
            lines = fh.readlines()
    except OSError:
        return [], [], False
    for line in lines:
        m = _SECTION.match(line)
        if m:
            section, sub = m.group(1).lower(), m.group(2)
            if sub is None and "." in section:  # old [remote.origin] syntax
                section, sub = section.split(".", 1)
            if sub is not None:
                sub = re.sub(r"\\(.)", r"\1", sub)
            if section in ("include", "includeif"):
                includes = True
            if section == "remote" and sub is not None:
                remotes.setdefault(sub, "")
            if section == "filter" and sub is not None and sub not in filters:
                filters.append(sub)
            line = m.group(3)
            if not line.strip() or line.lstrip()[:1] in ("#", ";"):
                continue
        if section == "remote" and sub is not None:
            kv = _KEYVAL.match(line)
            if kv and kv.group(1).lower() == "url" and not remotes[sub] and kv.group(2):
                remotes[sub] = kv.group(2).strip().strip('"')
    return list(remotes.items()), filters, includes


def remote_host(url: str) -> str:
    """Host name of a network remote, or "" for a folder on this computer."""
    url = url.strip()
    m = re.match(r"^([A-Za-z][A-Za-z0-9+.-]*)://(?:[^@/]*@)?(\[[^\]]+\]|[^/:]*)", url)
    if m:
        return "" if m.group(1).lower() == "file" else m.group(2).lower()
    if url.startswith(("/", ".", "~")):
        return ""
    m = re.match(r"^(?:[^@/:]+@)?([^/:]+):", url)  # scp syntax: user@host:path
    return m.group(1).lower() if m else ""


_PROTOCOLS = ("file", "git", "http", "https", "ssh", "ext")
# "git -c key=value" splits at the first "=", so a filter whose name holds "=" (or other
# odd characters) cannot be switched off from the command line: such a repository never
# gets "git status", the only command here that runs filters.
_SAFE_FILTER = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._+-]*$")


def _git_command(git: str, root: str, filters: Sequence[str]) -> List[str]:
    # An empty core.fsmonitor disables it both before git 2.36 (a hook path) and after.
    cmd = [git, "--no-pager", "-c", "safe.directory=*", "-c", "core.fsmonitor=",
           "-c", "core.untrackedCache=false", "-c", "protocol.allow=never"]
    for proto in _PROTOCOLS:
        cmd += ["-c", "protocol.%s.allow=never" % proto]
    for name in filters:  # the repository's own filter commands never run
        if not _SAFE_FILTER.match(name):
            continue  # inspect_repo never runs "git status" with one of these
        for key in ("clean", "smudge", "process"):
            cmd += ["-c", "filter.%s.%s=" % (name, key)]
        cmd += ["-c", "filter.%s.required=false" % name]
    return cmd + ["-C", root]


def _git_env(root: str) -> Dict[str, str]:
    env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
    env.update(GIT_OPTIONAL_LOCKS="0", GIT_TERMINAL_PROMPT="0", GIT_NO_LAZY_FETCH="1",
               GIT_PAGER="cat", PAGER="cat", LC_ALL="C", LANGUAGE="C")
    parent = os.path.dirname(root)
    if ":" not in parent:
        env["GIT_CEILING_DIRECTORIES"] = parent
    return env


class GitTimeout(Exception):
    pass


class GitCancelled(Exception):
    pass


def run_git(cmd: List[str], env: Dict[str, str], timeout: float,
            cancel: Optional[threading.Event] = None) -> Tuple[int, bytes, bytes]:
    proc = subprocess.Popen(cmd, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                            stderr=subprocess.PIPE, env=env, cwd="/", close_fds=True,
                            start_new_session=True)
    deadline = time.monotonic() + timeout
    while True:
        wait = deadline - time.monotonic()
        if cancel is not None:
            wait = min(wait, 0.2)  # look at the cancel button five times a second
        try:
            out, err = proc.communicate(timeout=max(wait, 0.01))
            return proc.returncode, out, err
        except subprocess.TimeoutExpired:
            cancelled = cancel is not None and cancel.is_set()
            if not cancelled and time.monotonic() < deadline:
                continue  # communicate() can be called again without losing output
            try:
                os.killpg(proc.pid, signal.SIGKILL)  # git may have started helpers
            except OSError:
                pass
            proc.communicate()
            raise GitCancelled() if cancelled else GitTimeout()


def parse_status(out: bytes) -> Dict[str, object]:
    """Parse ``git status --porcelain=v2 --branch -z`` (git 2.11 or later)."""
    info: Dict[str, object] = {"oid": "", "head": "", "changed": 0, "untracked": 0,
                               "untracked_dirs": 0, "ignored": [], "untracked_paths": []}
    records = out.split(b"\0")
    i = 0
    while i < len(records):
        rec = records[i]
        i += 1
        if not rec:
            continue
        kind = rec[:2]
        if rec.startswith(b"# branch.oid "):
            info["oid"] = rec[13:].decode("ascii", "replace")
        elif rec.startswith(b"# branch.head "):
            info["head"] = os.fsdecode(rec[14:])
        elif kind in (b"1 ", b"u "):
            info["changed"] += 1  # type: ignore[operator]
        elif kind == b"2 ":
            info["changed"] += 1  # type: ignore[operator]
            i += 1  # the original path of a rename
        elif kind == b"? ":
            info["untracked"] += 1  # type: ignore[operator]
            if rec.endswith(b"/"):
                info["untracked_dirs"] += 1  # type: ignore[operator]
                info["untracked_paths"].append(os.fsdecode(rec[2:]))  # type: ignore[union-attr]
        elif kind == b"! ":
            info["ignored"].append(os.fsdecode(rec[2:]))  # type: ignore[union-attr]
    return info


def _count_stashes(common_dir: str) -> int:
    try:
        with open(os.path.join(common_dir, "logs", "refs", "stash"), "rb") as fh:
            return sum(1 for line in fh if line.strip())
    except OSError:
        return 0


def _only_repositories(path: str, known: Optional[Set[str]], depth: int = 3) -> bool:
    """True when ``path`` holds nothing but other repositories or worktrees, such as
    ``.claude/worktrees/``, that the search found (each one is reported on its own).
    ``known=None`` accepts any repository."""
    try:
        names = os.listdir(path)
    except OSError:
        return False
    if ".git" in names:
        return known is None or os.path.normpath(path) in known
    if depth == 0 or not names:
        return False
    for name in names:
        full = os.path.join(path, name)
        if os.path.islink(full) or not os.path.isdir(full):
            return False
        if not _only_repositories(full, known, depth - 1):
            return False
    return True


def _kept_ignored(root: str, ignored: List[str], excl: Exclusions,
                  known: Optional[Set[str]] = None) -> List[str]:
    """Ignored paths that the backup copies and that are not just build output."""
    kept = []
    for rel in ignored[:_MAX_IGNORED]:
        is_dir = rel.endswith("/")
        clean = rel.rstrip("/")
        name = os.path.basename(clean)
        full = os.path.join(root, clean)
        if _REGENERABLE.search(clean):
            continue
        if excl.match(name, full, paths.home_relative(full), is_dir) is not None:
            continue
        if is_dir:
            try:
                listing = os.listdir(full)
            except OSError:
                continue
            if excl.match_listing(full, listing) is not None or _only_repositories(full, known):
                continue  # nested repositories and worktrees are reported on their own
        kept.append(rel)
    return kept


def _remote_of(ref: str, names: Sequence[str]) -> str:
    """Configured remote that owns ``refs/remotes/<ref>`` (names may contain "/")."""
    for name in names:  # longest first
        if ref.startswith(name + "/"):
            return name
    return ""


_GLOB_CHARS = re.compile(r"[*?\[\\]")


def inspect_repo(project: Project, git: Optional[str], excl: Exclusions,
                 timeout: float, cancel: Optional[threading.Event] = None,
                 known: Optional[Set[str]] = None) -> GitInfo:
    """State of one repository. ``known`` are the folders the search found as projects:
    a nested repository is left out of the parent's new files only when it is reported
    on its own."""
    info = GitInfo()
    started = time.monotonic()
    if project.common_dir is None:
        info.note = "A pasta .git está incompleta ou não se consegue ler"
        return info
    remotes, filters, _ = read_git_config(os.path.join(project.common_dir, "config"))
    info.remotes = [(name, remote_host(url)) for name, url in remotes]
    info.stashes = _count_stashes(project.common_dir)
    if git is None:
        info.note = "O git não está instalado: não foi possível ver o que falta enviar"
        return info
    try:
        owner = os.stat(project.path).st_uid
    except OSError:
        owner = os.getuid()
    info.foreign_owner = owner != os.getuid()
    env = _git_env(project.path)
    code, err = 0, b""
    try:
        code, out, _ = run_git(_git_command(git, project.path, ()) + [
            "config", "-z", "--get-regexp", r"^filter\..*\.(clean|smudge|process)$"],
            env, timeout, cancel)
        # 1 means "no filter at all"; anything else, and the list cannot be trusted.
        filters_known = code in (0, 1)
        if code == 0:
            for item in out.split(b"\0"):
                key = os.fsdecode(item.split(b"\n", 1)[0])
                if key.count(".") >= 2 and key[7:key.rfind(".")] not in filters:
                    filters.append(key[7:key.rfind(".")])
        unsafe_filters = not filters_known or any(not _SAFE_FILTER.match(n) for n in filters)
        cmd = _git_command(git, project.path, filters)
        code, out, err = run_git(cmd + ["for-each-ref", "--format=%(objectname) %(refname)",
                                        "refs/heads", "refs/remotes", "refs/stash"],
                                 env, timeout, cancel)
        if code != 0:
            info.note, info.detail = "O git não conseguiu ler este repositório", _first_line(err)
            return info
        heads: Dict[str, str] = {}
        names = sorted((n for n, _ in remotes), key=len, reverse=True)
        with_refs: Set[str] = set()
        for line in out.splitlines():
            oid, _, ref = line.partition(b" ")
            ref_s = os.fsdecode(ref)
            if ref_s.startswith("refs/heads/"):
                heads[ref_s[11:]] = oid.decode("ascii", "replace")
            elif ref_s.startswith("refs/remotes/") and not ref_s.endswith("/HEAD"):
                with_refs.add(_remote_of(ref_s[13:], names))
            elif ref_s == "refs/stash" and not info.stashes:
                info.stashes = 1
        # Only what reached a network remote (GitHub...) counts as sent: a bare
        # repository in another folder of this computer is lost with the computer.
        network = [n for n, host in info.remotes if host]
        sent_to = [n for n in network if n in with_refs]
        info.remote_refs = bool(sent_to) if network else bool(with_refs)
        if sent_to and not any(_GLOB_CHARS.search(n) for n in sent_to):
            against = ["--remotes=" + n for n in sent_to]
        else:
            against = ["--remotes"]

        detached = False
        if project.kind == KIND_BARE:
            pass
        elif info.foreign_owner:
            # Another user's configuration could run commands during "git status".
            info.note = "Pertence a outro utilizador: as alterações não foram verificadas"
        elif unsafe_filters:
            # Its filters could run commands during "git status" and cannot be disabled.
            info.note = ("Tem definições do git que não é seguro usar: as alterações não "
                         "foram verificadas")
        else:
            args = ["status", "--porcelain=v2", "--branch", "-z", "--ignore-submodules=dirty"]
            if project.home_repo:
                args += ["--untracked-files=no", "--ignored=no"]
            else:
                args += ["--untracked-files=normal", "--ignored=matching"]
            code, out, err = run_git(cmd + args, env, timeout, cancel)
            if code != 0:
                info.note, info.detail = "O git não conseguiu ver as alterações", _first_line(err)
                return info
            status = parse_status(out)
            info.changed = int(status["changed"])  # type: ignore[arg-type]
            nested = sum(1 for rel in status["untracked_paths"][:_MAX_IGNORED]  # type: ignore
                         if _only_repositories(os.path.join(project.path, rel.rstrip("/")),
                                               known))
            info.untracked = int(status["untracked"]) - nested  # type: ignore[arg-type]
            info.untracked_dirs = int(status["untracked_dirs"]) - nested  # type: ignore
            kept = _kept_ignored(project.path, status["ignored"], excl,  # type: ignore
                                 known)
            info.ignored, info.ignored_count = kept[:10], len(kept)
            head = str(status["head"])
            detached = head == "(detached)"
            info.detached = detached
            info.branch = "" if detached else head
            info.unborn = status["oid"] == "(initial)"

        include_head = [] if info.unborn or project.kind == KIND_BARE else ["HEAD"]
        branches = [] if project.worktree else ["--branches"]
        if project.worktree:
            heads = {b: o for b, o in heads.items() if b == info.branch}
        if not heads and not include_head:
            info.commits, info.unpushed = 0, 0
        elif not info.remote_refs:
            code, out, err = run_git(cmd + ["rev-list", "--count"] + include_head
                                     + branches, env, timeout, cancel)
            if code == 0:
                info.commits = int(out.strip() or b"0")
                info.unpushed = info.commits
                info.unpushed_branches = sorted(heads)
        else:
            code, out, err = run_git(cmd + ["rev-list"] + include_head + branches
                                     + ["--not"] + against, env, timeout, cancel)
            if code == 0:
                missing = {line.decode("ascii", "replace") for line in out.split()}
                info.unpushed = len(missing)
                # A branch has work to send exactly when its tip is not on a remote.
                info.unpushed_branches = sorted(b for b, oid in heads.items() if oid in missing)
                if detached and not info.unpushed_branches and missing:
                    info.unpushed_branches = ["HEAD"]
        if code != 0:
            info.note, info.detail = "O git não conseguiu contar os commits", _first_line(err)
            return info
        info.checked = True
    except GitTimeout:
        info.note = "O git demorou demasiado tempo a responder"
    except GitCancelled:
        info.note = "A procura foi cancelada"
    except OSError as exc:
        info.note = "Não foi possível executar o git"
        info.detail = str(exc.strerror or exc)
    finally:
        info.seconds = time.monotonic() - started
    return info


def _first_line(err: bytes) -> str:
    text = err.decode("utf-8", "replace").strip()
    return text.splitlines()[0][:200] if text else ""


def _add_worktrees(walker: _Walker) -> None:
    """Worktrees registered by the repositories found (AI tools often create them
    in hidden or temporary folders)."""
    commons = {p.common_dir for p in walker.found.values() if p.common_dir}
    for common in sorted(commons):
        base = os.path.join(common, "worktrees")
        try:
            names = sorted(os.listdir(base))
        except OSError:
            continue
        for name in names:
            try:
                with open(os.path.join(base, name, "gitdir"), "rb") as fh:
                    target = os.fsdecode(fh.read().strip())
            except OSError:
                continue
            root = os.path.dirname(os.path.normpath(target))
            if root in walker.found or not os.path.isdir(root):
                continue
            project = walker._add(root, KIND_GIT, None)
            if project is not None and project.gitdir is None:
                del walker.found[root]


