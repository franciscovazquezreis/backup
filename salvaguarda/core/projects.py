"""Find programming projects in the home folder and tell which ones exist only here.

Everything here is read-only. The walk never follows symbolic links, never enters
another disk or partition and skips what the backup itself never copies (the same
:class:`Exclusions`). The git commands run without network, without the optional locks
that would let ``git status`` rewrite the index, without file-system monitors and
without the repository's own filter commands.

The state of a repository comes from what git already knows locally (the remote-tracking
branches of the last fetch or push); nothing is fetched.
"""

