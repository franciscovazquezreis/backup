def coverage_roots(resolution) -> List[Tuple[str, str]]:
    """(path, label) of everything a backup copies in full, from selection.resolve()."""
    return [(s.path, s.label) for s in resolution.sources
            if not s.extra and not s.shallow_files]


def search_roots(resolution) -> List[str]:
    """Selected folders worth searching besides the home (not app settings)."""
    return [s.path for s in resolution.sources
            if s.kind in (KIND_FOLDER_SOURCE, KIND_PROJECT_SOURCE, KIND_XDG_SOURCE)
            and not s.extra and not s.shallow_files]


def _excluded_on_the_way(path: str, root: str, excl: Exclusions) -> str:
    """Label of the exclusion rule that skips ``path`` when copying ``root``."""
    rel = os.path.relpath(path, root)
    if rel == ".":
        return ""  # exclusions never apply to a selected folder itself
    current = root
    for part in rel.split(os.sep):
        current = os.path.join(current, part)
        hit = excl.match(part, current, paths.home_relative(current), True)
        if hit is not None:
            return hit[1]
    return ""


def apply_coverage(projects: Sequence[Project], roots: Sequence[Tuple[str, str]],
                   exclusions: Optional[Exclusions] = None) -> None:
    for project in projects:
        project.covered_by = project.excluded_by = project.commits_elsewhere = ""
        project.commits_covered_by = ""
        project.partial = False
        project.blocked = paths.is_blocked_source(project.path)
        for root, label in roots:
            if not paths.is_inside(project.path, root):
                continue
            rule = _excluded_on_the_way(project.path, root, exclusions) if exclusions else ""
            if rule:
                project.excluded_by = rule
                continue
            project.covered_by = label
            break
        if not project.covered:
            project.partial = any(paths.is_inside(root, project.path) for root, _ in roots)
        common = project.common_dir
        if (project.covered and common and project.kind == KIND_GIT
                and not paths.is_inside(common, project.path)
                and not any(paths.is_inside(common, root) for root, _ in roots)):
            project.commits_elsewhere = os.path.dirname(common) if os.path.basename(
                common) == ".git" else common
        if (not project.covered and project.worktree and common
                and not paths.is_inside(common, project.path)):
            for root, label in roots:
                if paths.is_inside(common, root):
                    project.commits_covered_by = label
                    break


def find_projects(roots: Sequence[Tuple[str, str]] = (), search: Sequence[str] = (),
                  exclusions: Optional[Exclusions] = None, limits: Optional[Limits] = None,
                  cancel: Optional[threading.Event] = None,
                  progress: Optional[Callable[[int, int, str], None]] = None,
                  git: Optional[str] = "", mounts: Optional[Dict[str, int]] = None,
                  skip: Sequence[str] = FINDER_SKIP,
                  table: Optional[Sequence[Tuple[str, int, str]]] = None) -> ScanResult:
    """Search the home folder (and selected folders it does not reach) for projects.

    ``roots`` are what the backup copies (:func:`coverage_roots`) and ``exclusions`` the
    rules it applies (``controller.make_exclusions``): together they say whether each
    project is in the backup. ``search`` are extra folders to search (:func:`search_roots`).
    The search itself always skips caches, dependencies and tools, whatever the
    settings, so that it stays fast. ``git=""`` looks git up in PATH, ``None`` means
    git is not available. ``mounts`` and ``table`` replace the system mount table (tests).

    It reads for a few seconds: call it from a worker thread, never from the GTK one, and
    hand ``progress`` updates to the interface with ``GLib.idle_add``.
    """
    limits = limits or Limits()
    home = paths.home()
    if git == "":
        git = shutil.which("git")
    search_excl = Exclusions()
    if table is None:
        table = mount_table()
    if mounts is None:
        mounts = {mnt: dev for mnt, dev, _ in table}
    walker = _Walker(home, search_excl, limits, cancel, progress, mounts, skip)
    extra = [os.path.normpath(r) for r in search]
    walker.watch = set(extra)
    walker.walk(home, "")
    # Selected folders the home walk did not list: outside the home, behind a symbolic
    # link, on another disk, too deep or inside a skipped folder. Folders on a network
    # share are left out: a server that stopped answering would block the search.
    home_net = network_mount(home, table)
    for root in extra:
        if root in walker.listed_watch or walker.result.cancelled:
            continue
        net = network_mount(root, table)
        if net and net != home_net:
            walker.result.network_skipped.append(root)
            continue
        walker.walk(root, paths.home_relative(root))
    _add_worktrees(walker)

    result = walker.result
    result.walk_seconds = time.monotonic() - walker.started
    result.git_available = git is not None
    projects = _dedupe(list(walker.found.values()), [r for r, _ in roots])
    apply_coverage(projects, roots, exclusions)

    repos = [p for p in projects if p.kind in (KIND_GIT, KIND_BARE)]
    known = set(walker.found)
    started = time.monotonic()
    deadline = started + limits.git_budget

    def job(project: Project) -> GitInfo:
        if cancel is not None and cancel.is_set():
            return GitInfo(note="A procura foi cancelada")
        if time.monotonic() > deadline:
            return GitInfo(note="Não houve tempo para verificar este repositório")
        return inspect_repo(project, git, search_excl, limits.git_timeout, cancel, known)

    checked = repos[:limits.max_repos]
    with ThreadPoolExecutor(max_workers=max(1, limits.workers)) as pool:
        for project, info in zip(checked, pool.map(job, checked)):
            project.git = info
    for project in repos[limits.max_repos:]:
        project.git = GitInfo(note="Há demasiados repositórios para verificar todos")
    # The stash is shared by all worktrees of a repository: report it once, on the
    # main work tree, when that one was found.
    mains = {p.common_dir for p in repos if not p.worktree and p.common_dir}
    for project in repos:
        if project.worktree and project.common_dir in mains and project.git is not None:
            project.git.stashes = 0
    result.git_seconds = time.monotonic() - started
    projects.sort(key=lambda p: (level_order(level(p)), p.covered, p.path.lower()))
    result.projects = projects
    return result


def _dedupe(projects: List[Project], root_paths: Sequence[str]) -> List[Project]:
    """The same folder reached twice (through a symbolic link): keep the selected path."""
    chosen: Dict[Tuple[int, int], Project] = {}
    order: List[Tuple[int, int]] = []
    loose: List[Project] = []
    for project in projects:
        try:
            st = os.stat(project.path)
        except OSError:
            loose.append(project)
            continue
        key = (st.st_dev, st.st_ino)
        other = chosen.get(key)
        if other is None:
            chosen[key] = project
            order.append(key)
        elif (any(paths.is_inside(project.path, r) for r in root_paths)
              and not any(paths.is_inside(other.path, r) for r in root_paths)):
            chosen[key] = project
    return [chosen[k] for k in order] + loose


# ---------------------------------------------------------------- wording for the UI
def level(project: Project) -> str:
    if project.kind == KIND_FOLDER:
        return LEVEL_LOCAL
    g = project.git
    if g is None:
        return LEVEL_UNKNOWN
    if not g.remotes or g.remote_refs is False:
        return LEVEL_LOCAL
    if not any(host for _, host in g.remotes):
        return LEVEL_LOCAL  # the only remotes are folders on this computer or a disk
    if (g.unpushed or g.changed or g.untracked or g.stashes):
        return LEVEL_LOCAL
    if not g.checked or (g.changed is None and project.kind != KIND_BARE):
        return LEVEL_UNKNOWN
    if g.ignored_count:
        return LEVEL_IGNORED
    return LEVEL_REMOTE


def level_order(value: str) -> int:
    return {LEVEL_LOCAL: 0, LEVEL_UNKNOWN: 1, LEVEL_IGNORED: 2, LEVEL_REMOTE: 3}.get(value, 4)


def _plural(n: int, one: str, many: str) -> str:
    return (one if n == 1 else many).format(n)


def _names(items: Sequence[str], limit: int = 3) -> str:
    shown = [paths.safe_text(i) for i in items[:limit]]
    text = ", ".join(shown)
    if len(items) > limit:
        text += " e mais {}".format(len(items) - limit)
    return text


def reasons(project: Project) -> List[str]:
    """Short sentences (PT-PT) that say why the project is or is not only here."""
    if project.kind == KIND_FOLDER:
        return ["Não usa git: não há outra cópia conhecida"]
    g = project.git or GitInfo()
    out: List[str] = []
    hosts = sorted({host for _, host in g.remotes if host})
    if project.kind == KIND_BARE:
        out.append("Repositório sem pasta de trabalho (bare), usado como remoto local")
    if not g.remotes:
        text = "Nunca foi enviado para o GitHub nem para outro remoto"
        if g.commits:
            text += _plural(g.commits, " (1 commit)", " ({} commits)")
        out.append(text)
    elif not hosts:
        out.append("O único remoto é uma pasta deste computador ou de um disco")
    elif g.remote_refs is False:
        out.append("Tem remoto ({}), mas ainda não foi enviado nada".format(", ".join(hosts)))
    if g.unpushed and g.remote_refs:
        text = _plural(g.unpushed, "1 commit por enviar", "{} commits por enviar")
        if g.unpushed_branches:
            text += " ({})".format(_names(g.unpushed_branches))
        out.append(text)
    elif g.commits and not g.remote_refs and g.remotes:
        out.append(_plural(g.commits, "1 commit só neste computador",
                           "{} commits só neste computador"))
    if g.changed:
        out.append(_plural(g.changed, "1 ficheiro alterado sem commit",
                           "{} ficheiros alterados sem commit"))
    if g.untracked:
        new_files, new_dirs = g.untracked - g.untracked_dirs, g.untracked_dirs
        parts = []
        if new_files:
            parts.append(_plural(new_files, "1 ficheiro novo", "{} ficheiros novos"))
        if new_dirs:
            parts.append(_plural(new_dirs, "1 pasta nova", "{} pastas novas"))
        out.append(" e ".join(parts) + " fora do git")
    if g.stashes:
        out.append(_plural(g.stashes, "1 conjunto de alterações posto de lado (git stash)",
                           "{} conjuntos de alterações postos de lado (git stash)"))
    if g.ignored_count:
        out.append("Ficheiros que o git ignora, só neste computador: {}".format(
            _names(g.ignored)))
    if history_elsewhere(project):
        out.append("Os commits estão em {}, que não vai para a cópia".format(
            paths.safe_text(paths.display_path(project.commits_elsewhere))))
    if g.note:
        out.append(g.note)
    if not out and g.checked:
        out.append("Está tudo no remoto ({})".format(", ".join(hosts)))
    return out


def history_elsewhere(project: Project) -> bool:
    """A copied worktree whose commits live in a main repository that is not copied, with
    commits that are on no remote: the copy holds the files but not that history."""
    g = project.git
    # Counts unknown (no git, out of time): a worktree always has commits of its own there.
    return bool(project.covered and project.commits_elsewhere
                and (g is None or not g.checked or g.unpushed or g.commits or g.stashes))


def in_backup(project: Project) -> bool:
    """True when the backup holds everything git cannot get back from a remote: the
    project is copied (with its commits), or it is a clean worktree whose commits are
    copied with the main repository."""
    if project.covered:
        return not history_elsewhere(project)
    g = project.git
    return bool(project.commits_covered_by and g is not None and g.changed == 0
                and g.untracked == 0 and not g.ignored_count)


def summary(result: ScanResult) -> Dict[str, int]:
    """Counts for the warning on the main page."""
    out = {"local_uncovered": 0, "local_covered": 0, "ignored_uncovered": 0, "unknown": 0}
    for p in result.projects:
        lv = level(p)
        if lv == LEVEL_LOCAL:
            out["local_covered" if in_backup(p) else "local_uncovered"] += 1
        elif lv == LEVEL_IGNORED and not p.covered:
            out["ignored_uncovered"] += 1
        elif lv == LEVEL_UNKNOWN:
            out["unknown"] += 1
    return out


def to_dict(result: ScanResult) -> Dict[str, object]:
    """JSON-friendly form for a cache in the state folder (paths written as ~/...)."""
    def proj(p: Project) -> Dict[str, object]:
        g = p.git
        return {
            "caminho": paths.to_portable(p.path), "tipo": p.kind, "marcadores": p.markers,
            "dentro_de": paths.to_portable(p.parent) if p.parent else None,
            "worktree": p.worktree, "submodulo": p.submodule, "coberto_por": p.covered_by,
            "parcial": p.partial, "excluido_por": p.excluded_by, "commits_noutro_sitio": p.commits_elsewhere,
            "bloqueado": p.blocked, "commits_copiados_por": p.commits_covered_by,
            "nivel": level(p), "motivos": reasons(p),
            "git": None if g is None else {
                "verificado": g.checked, "remotos": g.remotes, "enviado_algo": g.remote_refs,
                "ramo": g.branch, "por_enviar": g.unpushed, "ramos_por_enviar": g.unpushed_branches,
                "alterados": g.changed, "novos": g.untracked, "stash": g.stashes,
                "ignorados": g.ignored, "nota": g.note, "detalhe": g.detail,
                "segundos": round(g.seconds, 3),
            },
        }
    return {
        "projetos": [proj(p) for p in result.projects],
        "pastas": result.dirs, "entradas": result.entries,
        "segundos_procura": round(result.walk_seconds, 3),
        "segundos_git": round(result.git_seconds, 3),
        "incompleta": result.truncated, "demasiado_fundo": result.too_deep_count,
        "outros_discos": [paths.to_portable(p) for p in result.other_filesystems],
        "rede_por_procurar": [paths.to_portable(p) for p in result.network_skipped],
        "ilegiveis": result.unreadable_count,
    }
